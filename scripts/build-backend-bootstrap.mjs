import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')
const files=['migrations/202611090001_core.sql','migrations/202611090002_storage.sql','seed.sql']
const blocks=files.map(file=>{let sql=fs.readFileSync(path.join(root,'supabase',file),'utf8');if(file.startsWith('migrations/'))sql=sql.replace(/^begin;\s*/i,'').replace(/\s*commit;\s*$/i,'');return `-- Source: ${file}\n${sql}`})
fs.writeFileSync(path.join(root,'supabase/bootstrap.sql'),`-- PawsUp: one-time initialization for a NEW, empty Supabase project.\n-- Generated by npm run backend:bootstrap. Do not mix with CLI migration history.\n-- Entire setup is atomic; an error rolls back all changes.\nbegin;\n\n${blocks.join('\n\n')}\ncommit;\n`)
console.log('Generated supabase/bootstrap.sql')
